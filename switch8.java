public class switch8 {
    public static void main(String[] args) {
        char ch='g';
        switch(ch)
        {
            case 'a':
            System.out.println("Mango");
            break;
            case 'b':
            System.out.println("Apple");
            break;
            case 'd':
            System.out.println("Pineapple");
            break;
            default:
            System.out.println("Fruits not available");
        }
    }
    
}
